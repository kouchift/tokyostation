# ---- Wikidata 由来の補完（あれば）
wd = {}
p = "/tmp/poi/linemeta.json"
if os.path.exists(p):
    wd = json.load(open(p, encoding="utf-8"))

net = io.open("data/network.js", encoding="utf-8").read()
i = net.index(" lines: ") + len(" lines: ")
LINES = json.loads(net[i:net.index("\n", i)].rstrip(","))

def hashcolor(name):
    h = 0
    for ch in name: h = (h * 31 + ord(ch)) % 360
    return "hsl(%d,42%%,45%%)" % h

out = {}
stat = {"curated": 0, "wikidata": 0, "auto": 0}
for L in LINES:
    n = L["name"]
    if n in CURATED:
        c, k, o, cf = CURATED[n]
        out[n] = {"c": c, "k": k, "o": o, "conf": cf, "src": "各社公表のラインカラー"}
        stat["curated"] += 1
    elif n in wd and wd[n].get("c"):
        out[n] = {"c": wd[n]["c"], "k": wd[n].get("k", ""), "o": wd[n].get("o", ""),
                  "conf": "低", "src": "Wikidata P465（誤りの可能性あり・要確認）"}
        stat["wikidata"] += 1
    else:
        out[n] = {"c": hashcolor(n), "k": "", "o": wd.get(n, {}).get("o", ""),
                  "conf": "なし", "src": "自動生成色（公式色ではありません）"}
        stat["auto"] += 1
    out[n]["e"] = L["edges"]

io.open("data/lines_meta.js", "w", encoding="utf-8").write(
"""/* 路線メタ（自動生成: tools/build_lines_meta.py）
   c=表示色 k=路線記号 o=事業者 conf=色の確信度 src=色の出どころ e=区間数

   ■ 色について
   ラインカラーは「色そのもの（数値）」であり、各社が案内のために公表している情報です。
   本アプリはその値を再現していますが、ロゴ・シンボルマーク・キャラクター等の
   「意匠・図案」は著作権および商標権の対象のため一切収録していません。
   路線記号（G, M, JY など）は識別子であり、バッジは本アプリが独自に描画しています。
   ※conf が「低」「なし」の路線は色が正確でない可能性があります。各社公式で要確認。
*/
""" + "RG.LINEMETA = %s;\n" % json.dumps(out, ensure_ascii=False, separators=(",", ":")))
